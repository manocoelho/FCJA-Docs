def analisar_conformidade_fpr(ext: str, nome_arquivo: str = "") -> Dict[str, Any]:
    """
    Retorna a regra do FPR (Format Policy Registry) do Archivematica 1.18.0
    correspondente à extensão do arquivo.
    """
    ext_limpa = (ext or "").strip().lower().lstrip(".")
    if not ext_limpa and nome_arquivo and "." in nome_arquivo:
        ext_limpa = nome_arquivo.rsplit(".", 1)[-1].lower()

    regra = REGRAS_FPR_ARCHIVEMATICA.get(ext_limpa)
    if regra:
        return dict(regra)

    return {
        "ext": ext_limpa or "bin",
        "categoria": "Outros Formatos Registrados (PRONOM)",
        "descricaoFormato": f"Formato Digital (.{ext_limpa or 'bin'}) — Base PRONOM (1.639 versões)",
        "puidPronom": "PRONOM / Siegfried Auto-Detect",
        "acaoPreservacao": "Mantém bitstream original + manifesto SHA-256 no AIP",
        "formatoPreservacao": f"Original (.{ext_limpa or 'bin'})",
        "acaoAcesso": "Mantém bitstream original para download controlado",
        "formatoAcesso": f"Original (.{ext_limpa or 'bin'})",
        "ferramentaIdentificacao": "Siegfried (PRONOM)",
        "ferramentaValidacao": "Siegfried + Fixity SHA-256",
        "aceitoFpr": True,
    }


def mapear_dc_type_dcmi(ext: str, formato_mime: str = "") -> str:
    """
    Mapeia a extensão ou MIME type para o vocabulário controlado DCMI Type
    exigido pela coluna dc.type do metadata.csv do Archivematica 1.18.0:
    Text, Image, Sound, MovingImage, Dataset, Collection.
    """
    ext_l = (ext or "").strip().lower().lstrip(".")
    mime_l = (formato_mime or "").strip().lower()

    if ext_l in ("xlsx", "xls", "ods", "csv") or "spreadsheet" in mime_l or "excel" in mime_l:
        return "Dataset"
    if ext_l in ("png", "jpg", "jpeg", "tif", "tiff", "bmp", "gif", "svg", "webp") or mime_l.startswith("image/"):
        return "Image"
    if ext_l in ("wav", "mp3", "ogg", "flac", "aac", "m4a") or mime_l.startswith("audio/"):
        return "Sound"
    if ext_l in ("mp4", "avi", "mov", "mkv", "webm", "wmv") or mime_l.startswith("video/"):
        return "MovingImage"
    if ext_l in ("zip", "tar", "gz", "7z"):
        return "Collection"
    return "Text"
